// Builds assets/atlas.png, assets/atlas.json and src/sim/anims.js from the dragongame BMP pack.
// Usage: node tools/build-atlas.mjs [--source <dir>] [--out <repo-root>]
//   source: --source, else DRAGONGAME_ASSETS, else manifest.sourceRoot
//   out:    root that receives assets/ and src/sim/ (default: this repo)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { posix } from 'node:path';
import { pathToFileURL } from 'node:url';
import { decodeBmp } from './lib/bmp.mjs';
import { encodePng } from './lib/png.mjs';
import { REPO_ROOT, argValue, loadManifest, resolveSourceRoot } from './lib/source.mjs';

export const ATLAS_WIDTH = 512;
export const PADDING = 1;
/** Plain lists: 6 sim ticks (60 Hz) per frame. FANCY durations are in 30 Hz ticks, so they are doubled. */
export const DEFAULT_TICKS = 6;
export const FANCY_TICK_SCALE = 2;

/**
 * Parse a sequence .txt. Tokens are whitespace separated (CRLF, blank lines, trailing spaces and a
 * missing final newline all vanish). A leading FANCY token means `name N` pairs.
 * Returns [{ file, ticks }] with file relative to the .txt.
 */
export function parseSequence(text) {
  const tokens = text.split(/\s+/).filter(Boolean);
  const fancy = tokens[0] === 'FANCY';
  if (fancy) tokens.shift();
  const out = [];
  if (fancy) {
    if (tokens.length % 2 !== 0) throw new Error('FANCY sequence has an odd number of tokens');
    for (let i = 0; i < tokens.length; i += 2) {
      const n = Number(tokens[i + 1]);
      if (!Number.isInteger(n) || n < 1) throw new Error(`FANCY duration "${tokens[i + 1]}" for ${tokens[i]} is not a positive integer`);
      out.push({ file: tokens[i], ticks: n * FANCY_TICK_SCALE });
    }
  } else {
    for (const file of tokens) out.push({ file, ticks: DEFAULT_TICKS });
  }
  return out;
}

/**
 * Shelf packer. rects: [{ key, w, h }]. Items go on shelves tallest first; every item reserves
 * `padding` px to its right and below. Returns { width, height, placed: Map key -> {x,y,w,h} }.
 */
export function packShelves(rects, width = ATLAS_WIDTH, padding = PADDING) {
  const sorted = [...rects].sort((a, b) => b.h - a.h || b.w - a.w || (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  const placed = new Map();
  let x = 0, y = 0, shelfH = 0, usedH = 0;
  for (const r of sorted) {
    if (r.w > width) throw new Error(`frame ${r.key} (${r.w}px) is wider than the atlas (${width}px)`);
    if (x + r.w > width) { // new shelf
      y += shelfH + padding;
      x = 0;
      shelfH = 0;
    }
    placed.set(r.key, { x, y, w: r.w, h: r.h });
    x += r.w + padding;
    shelfH = Math.max(shelfH, r.h);
    usedH = Math.max(usedH, y + r.h);
  }
  return { width, height: Math.max(usedH, 1), placed };
}

function formatJson(frames, anims) {
  const lines = ['{', '  "frames": {'];
  const fk = Object.keys(frames);
  fk.forEach((k, i) => lines.push(`    ${JSON.stringify(k)}: ${JSON.stringify(frames[k]).replace(/([:,])/g, '$1 ')}${i < fk.length - 1 ? ',' : ''}`));
  lines.push('  },', '  "anims": {');
  const ak = Object.keys(anims);
  ak.forEach((k, i) => lines.push(`    ${JSON.stringify(k)}: ${JSON.stringify(anims[k]).replace(/([:,])/g, '$1 ')}${i < ak.length - 1 ? ',' : ''}`));
  lines.push('  }', '}');
  return lines.join('\n') + '\n';
}

export function formatAnimsJs(anims) {
  const lines = [
    '// Generated by tools/build-atlas.mjs from tools/manifest.json. Do not edit.',
    '// Per-frame durations in 60 Hz sim ticks for every atlas animation.',
    'export const ANIMS = {',
  ];
  for (const name of Object.keys(anims)) lines.push(`  ${JSON.stringify(name).replace(/"/g, "'")}: { ticks: [${anims[name].ticks.join(', ')}] },`);
  lines.push('};');
  return lines.join('\n') + '\n';
}

/**
 * Colour channel swap of a manifest entry (`"swap": "rg"`): two distinct channels of r, g, b.
 * Returns [i, j] channel indexes, or null when the entry has no swap.
 */
export function parseSwap(swap) {
  if (swap === undefined) return null;
  const m = typeof swap === 'string' && /^([rgb])([rgb])$/.exec(swap);
  if (!m || m[1] === m[2]) throw new Error(`bad swap "${swap}" (two different channels of r, g, b, like "rg")`);
  return ['rgb'.indexOf(m[1]), 'rgb'.indexOf(m[2])];
}

/** Swap two channels of every pixel of an RGBA buffer in place. */
export function swapChannels(rgba, [i, j]) {
  for (let p = 0; p < rgba.length; p += 4) {
    const v = rgba[p + i];
    rgba[p + i] = rgba[p + j];
    rgba[p + j] = v;
  }
  return rgba;
}

/**
 * Resolve the manifest into anims: name -> [{ key, file, swap, ticks }]. `file` is the BMP path
 * relative to the source root; `key` is the frame key, the same path, plus `#<swap>` for an
 * entry with a channel swap so recoloured frames do not collide with the originals.
 */
export function resolveEntries(manifest, sourceRoot) {
  const anims = new Map();
  const add = (e, frames) => {
    if (anims.has(e.name)) throw new Error(`duplicate manifest name "${e.name}"`);
    if (!frames.length) throw new Error(`manifest entry "${e.name}" has no frames`);
    parseSwap(e.swap);
    const suffix = e.swap ? `#${e.swap}` : '';
    anims.set(e.name, frames.map((f) => ({ key: f.file + suffix, file: f.file, swap: e.swap, ticks: f.ticks })));
  };
  for (const e of manifest.entries) {
    if (e.list) {
      const dir = posix.dirname(e.list);
      const text = readFileSync(join(sourceRoot, e.list), 'utf8');
      add(e, parseSequence(text).map((f) => ({ file: posix.normalize(posix.join(dir, f.file)), ticks: f.ticks })));
    } else if (e.files) {
      add(e, e.files.map((f) => ({ file: posix.normalize(f), ticks: DEFAULT_TICKS })));
    } else if (e.file) {
      add(e, [{ file: posix.normalize(e.file), ticks: DEFAULT_TICKS }]);
    } else {
      throw new Error(`manifest entry "${e.name}" needs list, files or file`);
    }
  }
  return anims;
}

/** Pure build: returns { png, atlasJson, animsJs, width, height, frameCount }. */
export function buildAtlas(manifest, sourceRoot) {
  const entries = resolveEntries(manifest, sourceRoot);
  const decoded = new Map();
  for (const frames of entries.values()) {
    for (const { key, file, swap } of frames) {
      if (decoded.has(key)) continue;
      const path = join(sourceRoot, file);
      if (!existsSync(path)) throw new Error(`missing frame ${file} (looked in ${sourceRoot})`);
      let d;
      try {
        d = decodeBmp(readFileSync(path));
      } catch (e) {
        throw new Error(`${file}: ${e.message}`);
      }
      if (swap) swapChannels(d.rgba, parseSwap(swap));
      decoded.set(key, d);
    }
  }
  const { width, height, placed } = packShelves([...decoded].map(([key, d]) => ({ key, w: d.width, h: d.height })));
  const rgba = new Uint8Array(width * height * 4);
  for (const [key, d] of decoded) {
    const p = placed.get(key);
    for (let row = 0; row < d.height; row++) {
      rgba.set(d.rgba.subarray(row * d.width * 4, (row + 1) * d.width * 4), ((p.y + row) * width + p.x) * 4);
    }
  }
  const frames = {};
  for (const key of [...decoded.keys()].sort()) frames[key] = placed.get(key);
  const anims = {};
  for (const name of [...entries.keys()].sort()) {
    const list = entries.get(name);
    anims[name] = { frames: list.map((f) => f.key), ticks: list.map((f) => f.ticks) };
  }
  return {
    png: encodePng(width, height, rgba),
    atlasJson: formatJson(frames, anims),
    animsJs: formatAnimsJs(anims),
    width,
    height,
    frameCount: decoded.size,
  };
}

function main(argv) {
  const manifest = loadManifest();
  const sourceRoot = resolveSourceRoot(manifest, argv);
  if (!existsSync(sourceRoot)) {
    console.error(`build-atlas: source folder not found: ${sourceRoot}\nUse --source <dir> or set DRAGONGAME_ASSETS.`);
    process.exit(1);
  }
  const outRoot = resolve(argValue(argv, '--out') || REPO_ROOT);
  const out = buildAtlas(manifest, sourceRoot);
  const targets = [
    ['assets/atlas.png', out.png],
    ['assets/atlas.json', out.atlasJson],
    ['src/sim/anims.js', out.animsJs],
  ];
  for (const [rel, data] of targets) {
    const path = join(outRoot, rel);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, data);
  }
  console.log(`atlas ${out.width}x${out.height}, ${out.frameCount} frames, ${Object.keys(JSON.parse(out.atlasJson).anims).length} anims -> ${outRoot}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main(process.argv.slice(2));
